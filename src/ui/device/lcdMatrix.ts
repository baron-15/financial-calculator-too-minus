/** Number of character cells. */
export const MATRIX_CELLS = 3;

/**
 * Split text into display characters: one per cell, with a combining macron kept on its letter
 * (NFD turns the precomposed ȳ into y + macron, the same form as x̄).
 */
export function matrixChars(text: string): string[] {
  const out: string[] = [];
  for (const ch of text.normalize("NFD")) {
    if (ch === MACRON && out.length > 0) out[out.length - 1] += ch;
    else out.push(ch);
  }
  return out;
}

/** The lit dots of one character as [column, row] pairs (0-based), or null if there is no glyph. */
export function matrixDots(ch: string): [number, number][] | null {
  const bitmap = FONT[ch];
  if (!bitmap) return null;
  const dots: [number, number][] = [];
  bitmap.forEach((row, r) => {
    for (let c = 0; c < 5; c++) if (row[c] === "1") dots.push([c, r]);
  });
  return dots;
}

